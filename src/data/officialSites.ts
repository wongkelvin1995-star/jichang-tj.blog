/**
 * 品牌官网资料：只收站长指定的三家（FLY V、灵动云、隐形人）。
 * 1. 官网地址由站长提供；链接是普通外链，不带推广参数。推广链接仍然只在 brands.ts 的 affiliate_url。
 * 2. “官网自述”和“官网上能找到”是 2026-11-04 在本站之外打开官网首页、价格页看到的内容，属于品牌自己的说法，本站没有测试；官网改版后要重新核对。
 * 3. price_check 是把官网页面和 planPrices.ts 逐项对照的结果；不同的地方如实写在 differences 里。
 *    站长 2026-11-04 指定以三个注册入口（brands.ts 里的推广链接）对应的结算页价格为准，所以价格表不按官网页面改，
 *    differences 只说明差异并写“以结算页为准”。本站没有各品牌的账号，打开链接只到登录页，没能独立核验结算页价格。
 *    以后站长在结算页发现价格表有误，改 planPrices.ts，同时更新或删掉这里对应的条目。
 * 4. 不引用官网上的安装包直链、优惠码以外的促销话术、SLA、零日志之类无法核验的宣传语。
 */
export interface OfficialSite {
  brand_id: string;
  url: string;
  host: string;
  /** 品牌自己的英文写法，与 brands.ts 的中文名不同时才填（如 FLY V），用在“官网是哪个”的标题里 */
  official_name?: string;
  /** 本站打开官网页面核对的日期 */
  checked_on: string;
  /** 官网自述，品牌自己的说法，本站未测试 */
  claims: string[];
  /** 官网上能找到的栏目 */
  sections: string[];
  /** 下单前可以到官网核对、或需要留意的事 */
  tips: string[];
  /** “官网是哪个”一句话：只转述官网自己对官方地址的说法，不点名别的网站，不下“冒充”之类的结论 */
  which_is_official: string;
  /** 本站自己的补充说明（不是品牌自述），例如“官网页面里没有对官方域名的单独说明”；没有就不填 */
  which_is_official_note?: string;
  /** 官网页面与本站价格表对照的结果 */
  price_check: {
    matched: string;
    differences: string[];
    /** 没能对照的档位，没有就不填 */
    not_compared?: string;
  };
}

