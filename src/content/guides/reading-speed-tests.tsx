/**
 * 机场测速图怎么看。
 * 不写“丢包率可达多少”“通常多少倍率”这类没有来源的数字；丢包对速度的影响用公开的经验公式（Mathis 等，1997）现算，
 * 延迟例子取自站长提供的灵动云检测记录（src/data/brandTests.ts，品牌页 #tests）。
 */
const MSS_BITS = 1460 * 8;

/** 经验公式：单条 TCP 连接的速度上限（Mbps）≈ 1.22 × MSS ÷（RTT × √丢包率）；这是 Reno 类拥塞控制的模型值，不是实测 */
function mathisMbps(rttMs: number, loss: number): string {
  return ((1.22 * MSS_BITS) / ((rttMs / 1000) * Math.sqrt(loss)) / 1e6).toFixed(2);
}

