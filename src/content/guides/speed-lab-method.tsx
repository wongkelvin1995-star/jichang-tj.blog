import React from 'react';
import { H2, P, Ul, Ol, Table, Callout, GuideLink, Faq } from '@/components/guide/Prose';
import { BRAND_TESTS } from '@/data/brandTests';

export default function SpeedLabMethod() {
  const rec = BRAND_TESTS.find((t) => t.brand_id === 'lingdongyun')!;
  const nodeRange = rec.scope.replace(/^订阅内全部\s*/, '');

  return (
    <>
      <P>
        测速结果很容易被误读：同一条线路，早上和晚上、电信和联通、这个工具和那个工具，数字可以差出几倍。所以测速实验室不比数字大小，只做一件事：把一次测试的条件和限制写清楚，让别人知道这个结果在什么条件下才成立。本文说明我们怎么记录，并用站长提供的一份真实检测记录做示例。
      </P>

      <H2 id="why">为什么先写条件，再写结果</H2>
      <P>
        一个“延迟 30ms”的结果，如果不知道是哪个工具、测的是到入口还是到目标网站、在哪个城市哪家运营商下测的，就没有任何参考价值。条件决定了结果能不能拿去比较，所以记录里条件在前、结果在后，限制紧跟着结果。
      </P>

      <H2 id="fields">七项必须记录的内容</H2>
      <Table
        nowrapFirst
        head={['项目', '怎么记', '示例（灵动云 2026-11-01 记录）']}
        rows={[
          ['测试时间', '精确到日期，最好写明时段', rec.tested_at],
          ['测试者', '谁测的、谁提供的记录', `${rec.tester}提供`],
          ['工具名称和版本', '写全名，版本号照界面抄；没有就写“版本未记录”', `${rec.tool.split('；')[0]}；${rec.tool_version ?? '版本未记录'}`],
          ['线路和节点范围', '订阅里有多少节点，测了哪些地区', nodeRange],
          ['测试环境', '城市、运营商、设备、客户端、内核', `${rec.network}；设备、客户端、内核${rec.environment_extra.device === null ? '未记录' : ''}`],
          ['结果', '只转述原图里读得到的内容', '见下一节'],
          ['限制', '这次没测什么，结论在什么条件下不成立', '没测下载和上传速度；只是一次检测']
        ]}
      />

      <H2 id="example">用这条记录演示怎么读</H2>
      <P>
        这份记录里有一个容易被误读的数：TLS RTT。{rec.findings[0]}把前者当成“网页打开有多快”，会得出完全错误的结论。
      </P>
      <P>
        再看限制：{rec.not_covered[0]}{rec.not_covered[1]}记录的完整内容{rec.image ? '和原图' : '（原图待更新中）'}，见<GuideLink href="/speed-lab/">测速实验室</GuideLink>和<GuideLink href="/airports/lingdongyun/#tests">灵动云品牌页</GuideLink>。
      </P>

      <H2 id="no">实验室不做的三件事</H2>
      <Ul
        items={[
          '不平均：不把不同时间、不同网络的结果算成“平均速度”。',
          '不排名：排名需要同一时间、同一网络、同一工具、同一批节点下反复测试，这些条件本站目前都不具备。',
          '不收没有原始依据的数字，也不用模拟数据代替：没有原始截图或导出文件的，页面写“待更新”。'
        ]}
      />

      <H2 id="trust">怎么判断别人发的“测速结果”能不能信</H2>
      <Ol
        items={[
          '有没有写测试时间。',
          '有没有写工具名称和版本。',
          '写没写测的是哪些节点、哪些地区。',
          '写没写在哪个城市、哪家运营商下测的。',
          '有没有原始截图或导出文件，而不是只有一句结论。',
          '有没有写限制，比如没测下载速度、只测了一次。'
        ]}
      />
      <P>
        缺两项以上的，当作传闻看待，不要据此做付款决定。怎么看别人发的测速图，见<GuideLink href="/guides/reading-speed-tests/">机场测速报告怎么看</GuideLink>。
      </P>

      <H2 id="template">提交记录时可以套用的格式</H2>
      <P>
        自己测过、想让本站收录，可以照下面的格式写，方括号里换成你自己的情况；写不出来的项，直接写“未记录”，不要猜。
      </P>
      <Ul
        items={[
          '测试时间：[日期和时段]',
          '测试者：[姓名或昵称]',
          '工具：[名称和版本号]',
          '线路和节点：[订阅里共多少个节点，测了哪几个地区]',
          '测试环境：[城市、运营商、设备、客户端和版本、内核]',
          '结果：[附原始截图或工具导出的文件]',
          '限制：[这次没测什么，一共测了几次]'
        ]}
      />

      <H2 id="submit">怎么向本站提交记录</H2>
      <P>
        把上面七项写清楚，附上原始截图或工具导出的文件（遮住订阅链接和账号信息），发到页面底部的纠错邮箱。记录里写不清的项，页面会标“未记录”；没有原始依据的数字，不收录。具体要求见<GuideLink href="/speed-lab/">测速实验室</GuideLink>。
      </P>

      <H2 id="faq">常见问题</H2>
      <Faq
        items={[
          {
            q: '为什么目前只有一条记录？',
            a: '因为本站目前只收到这一份有原始截图的检测记录。没有原始数据的品牌，页面写“暂无记录”，等整理好之后再更新，不会用模拟结果去补。'
          },
          {
            q: '为什么不给品牌测速排名？',
            a: '缺条件的排名，比没有排名更误导人。一条线路早晚、不同运营商下的结果可以差几倍，只测一次的数字不能拿来排序。'
          }
        ]}
      />

      <Callout title="本文的边界" tone="warn">
        示例记录只代表它自己的测试条件，不代表该品牌的整体表现；本文不对任何品牌的速度和稳定性下结论。
      </Callout>
    </>
  );
}
