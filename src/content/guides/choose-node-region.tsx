import React from 'react';
import { H2, P, Ol, Table, Callout, GuideLink, Faq } from '@/components/guide/Prose';
import { Flow } from '@/components/guide/Media';
import { BRAND_MD } from '@/data/brandMd';
import { BRAND_TESTS } from '@/data/brandTests';

const CORE_REGIONS = ['香港', '台湾', '日本', '新加坡', '美国'];
const OTHER_REGIONS = ['英国', '德国', '韩国', '法国', '马来西亚', '泰国', '土耳其', '印度', '菲律宾', '越南', '阿根廷'];

export default function ChooseNodeRegion() {
  const rec = BRAND_TESTS.find((t) => t.brand_id === 'lingdongyun')!;
  const countOf = (name: string) => BRAND_MD.filter((b) => (b.nodes.regions ?? '').includes(name)).length;
  const coreAll = CORE_REGIONS.every((r) => countOf(r) === BRAND_MD.length);
  const others = OTHER_REGIONS.map((r) => ({ r, n: countOf(r) }))
    .filter((x) => x.n > 0)
    .sort((a, b) => b.n - a.n)
    .slice(0, 6);

  return (
    <>
      <P>
        选节点地区，最常见的做法是“哪个地区延迟低就用哪个”，或者“看流媒体要哪个地区就选哪个”。这两个出发点都对，但都不完整：延迟要在自己的网络里测，不能按地图上的距离猜；服务要看出口落在哪里，不能只看节点名。本文先看站内资料里各家写了哪些地区，再按用途给出选择依据，最后给出一个不依赖猜测的试节点办法。
      </P>
      <Flow
        steps={[
          { title: '写下用途', note: '浏览、流媒体、AI、游戏、下载' },
          { title: '按用途定地区', note: '服务以官方说明为准' },
          { title: '该地区试两三个节点', note: '同一时段各测一次' },
          { title: '确认出口地区', note: '用 IP 归属地查询核对' },
          { title: '固定一两个常用节点', note: '记下测试时间和结果' }
        ]}
        caption="选节点地区的五步"
      />

      <H2 id="data">站内资料里写了哪些地区</H2>
      <P>
        站长提供的机场资料里，{coreAll ? `全部 ${BRAND_MD.length} 家` : '多数品牌'}都写了{CORE_REGIONS.join('、')}这五个地区；其余地区各家不一样：{others.map((x) => `${x.r} ${x.n} 家`).join('、')}（资料里列出了地区名的才算，有的资料以“等”结尾，没有列全）。这是品牌自己的标注，本站没有逐个节点测试，所以“有这个地区”只说明资料里写了，不说明质量。
      </P>

      <H2 id="by-use">按用途怎么选</H2>
      <Table
        nowrapFirst
        head={['用途', '选择依据', '怎么验证']}
        rows={[
          ['日常浏览和办公', '选延迟低、稳定的节点；地区只是参考，实际延迟看入口和线路', '同一地区试两三个节点，记下延迟，再用网页打开速度对照'],
          ['流媒体', '先确定要看哪个地区的内容，该服务在哪些地区提供、内容库有什么不同，以服务官方说明为准', '选出口在目标地区的节点，用检测结果和 IP 归属地核对落地地区'],
          ['AI 工具', '服务对可用地区有限制，以官方公布的支持地区为准，不要依赖第三方整理的清单', '确认出口在支持的地区，再实际登录使用一次'],
          ['在线游戏和语音', '看延迟和抖动，还要看节点是否支持转发 UDP', '用游戏自带的延迟显示，在不同时段各看几次'],
          ['下载和更新', '看带宽，同时留意节点的倍率会让流量额度消耗得更快', '先小文件试速，再确认倍率写法']
        ]}
      />

      <H2 id="distance">为什么不能只看地图上的距离</H2>
      <P>
        站长提供的灵动云 {rec.tested_at} 检测记录里，{rec.findings[0]}这些数字是珠海联通宽带下的一次检测。可以看到，新加坡节点的握手延迟比香港和台湾还低，这和“离得越近延迟越低”的直觉不一致。原因在于测的是到入口的延迟，入口设在哪里、怎么走线，记录里没有写明。所以地区名只是起点，实际要用自己的网络测。
      </P>

      <H2 id="try">一个不靠猜的试节点办法</H2>
      <Ol
        items={[
          '先选定一个用途，只围绕这个用途测，不要什么都测。',
          '在目标地区挑两三个节点，在同一个时段各测一次延迟，再各打开同样的几个网页。',
          '用 IP 归属地查询，确认出口真的在目标地区，做法见入口和出口那一篇。',
          '记下测试时间、节点名和结果，晚高峰前后各再测一次，只有一个时段的结果不能当结论。',
          '选出一两个表现稳定的常用节点，其余作为备用，不要频繁来回切换。'
        ]}
      />

      <H2 id="mistakes">最容易出错的几件事</H2>
      <Ol
        items={[
          '只看节点名里的地区，不核对出口。',
          '凭“哪个地区近”就下结论，没有在自己的网络里测。',
          '因为某个地区节点数量多，就默认它质量好，节点数量只说明可选的多。',
          '只测一次、只在一个时段测，就把结果当成长期结论。'
        ]}
      />

      <H2 id="faq">常见问题</H2>
      <Faq
        items={[
          {
            q: '同一个地区的几个节点，速度为什么差别很大？',
            a: '节点所在的服务器、当时的使用人数和入口线路都可能不同，所以同一地区要多试几个，用同样的方法比较。'
          },
          {
            q: '美国节点是不是一定很慢？',
            a: '在上面那份记录里，美国节点的握手延迟最高，这符合距离更远的直觉，但只代表那次的测试条件。是否影响使用，要看你的用途：浏览网页能接受的延迟，玩游戏未必能接受。'
          }
        ]}
      />

      <P>
        相关阅读：<GuideLink href="/guides/entry-and-exit-nodes/">入口和出口</GuideLink>讲了为什么节点名不等于出口地区，<GuideLink href="/guides/iplc-vs-iepl/">IPLC 和 IEPL 的区别</GuideLink>讲了线路标注怎么读。
      </P>

      <Callout title="本文的边界" tone="warn">
        本文不推荐某个地区，也不判断任何服务商的节点质量。各服务在不同地区的可用性随时可能变化，以服务的官方说明为准；示例只代表它自己的测试条件。
      </Callout>
    </>
  );
}
